// Builds a2ui/v1/catalog.json and src/a2ui/a2ui_catalog.ts from the A2UI 1.0 basic catalog.
// Usage: node scripts/a2ui-catalog.mjs <a2ui checkout>/catalogs/basic/v1/catalog.json
import { readFileSync, writeFileSync } from "node:fs";

const CATALOG_ID = "https://raw.githubusercontent.com/Artui/agents-web-components/main/a2ui/v1/catalog.json";
const COMPONENTS = [
  "Text",
  "Image",
  "Icon",
  "Row",
  "Column",
  "List",
  "Card",
  "Divider",
  "Button",
  "TextField",
  "CheckBox",
  "ChoicePicker",
];
const FUNCTIONS = [
  "required",
  "regex",
  "length",
  "numeric",
  "email",
  "formatString",
  "formatNumber",
  "formatCurrency",
  "formatDate",
  "pluralize",
  "openUrl",
  "and",
  "or",
  "not",
];

// Whole descriptions where the first sentence leaves out the syntax.
const WHOLE = new Set(["formatString"]);
// What the short $ref names mean; the render guide covers @path, @call and templates.
const TYPES = {
  DynamicString: 'a string, {"@path": pointer} or {"@call": name, "args": {...}}',
  DynamicNumber: "a number, @path or @call",
  DynamicBoolean: "a boolean, @path or @call",
  DynamicStringList: "a string array, @path or @call",
  DynamicValue: "any JSON value, @path or @call",
  DataBinding: '{"@path": pointer}',
  FunctionCall: '{"@call": name, "args": {...}}',
  Child: "a component id",
  ChildList: 'an array of component ids, or {"componentId": id, "path": pointer} to repeat one per array item',
  Action: '{"event": {"name": string, "context": {...}}} sent to you, or {"functionCall": FunctionCall} run here',
  CheckRule:
    '{"condition": DynamicBoolean, "message": string}; the message shows while the condition is false',
};

const source = JSON.parse(readFileSync(process.argv[2], "utf8"));

function sentence(text) {
  if (typeof text !== "string") {
    return undefined;
  }
  const end = text.search(/\.(\s|$)/);
  return end === -1 ? text : text.slice(0, end + 1);
}

function compact(schema) {
  const out = {};
  if (typeof schema.$ref === "string") {
    const name = schema.$ref.split("/").pop();
    if (name === "Weight") {
      return { type: "number" };
    }
    out.$ref = name;
  }
  for (const key of ["type", "enum", "default", "const"]) {
    if (schema[key] !== undefined) {
      out[key] = schema[key];
    }
  }
  if (schema.oneOf !== undefined) {
    out.oneOf = schema.oneOf.map(compact);
  }
  if (schema.items !== undefined) {
    out.items = compact(schema.items);
  }
  if (schema.properties !== undefined) {
    out.properties = Object.fromEntries(
      Object.entries(schema.properties).map(([name, value]) => [name, compact(value)]),
    );
    if (schema.required !== undefined) {
      out.required = schema.required;
    }
  }
  const description = sentence(schema.description);
  if (description !== undefined) {
    out.description = description;
  }
  return out;
}

function flatten(schema) {
  const parts = schema.allOf ?? [schema];
  const properties = {};
  const required = [];
  let checkable = false;
  for (const part of parts) {
    if (part.$ref?.endsWith("/Checkable")) {
      checkable = true;
      continue;
    }
    for (const [name, value] of Object.entries(part.properties ?? {})) {
      if (name !== "component") {
        properties[name] = compact(value);
      }
    }
    required.push(...(part.required ?? []).filter((name) => name !== "component"));
  }
  if (checkable) {
    properties["@checks"] = { type: "array", items: { $ref: "CheckRule" } };
  }
  const out = { properties, required };
  const description = sentence(schema.description);
  if (description !== undefined) {
    out.description = description;
  }
  return out;
}

function fn(name, schema) {
  const args = schema.properties.args;
  return {
    description: WHOLE.has(name) ? schema.description : sentence(schema.description),
    returnType: schema.returnType,
    args: Object.fromEntries(
      Object.entries(args.properties ?? {}).map(([name, value]) => [name, compact(value)]),
    ),
    required: args.required ?? [],
  };
}

const catalog = {
  catalogId: CATALOG_ID,
  protocolVersion: "1.0",
  components: Object.fromEntries(COMPONENTS.map((name) => [name, flatten(source.components[name])])),
  functions: Object.fromEntries(FUNCTIONS.map((name) => [name, fn(name, source.functions[name])])),
  types: TYPES,
};

writeFileSync("a2ui/v1/catalog.json", `${JSON.stringify(catalog, null, 2)}\n`);
writeFileSync(
  "src/a2ui/a2ui_catalog.ts",
  `// Generated by scripts/a2ui-catalog.mjs from the A2UI 1.0 basic catalog; edit the script, not this.\n` +
    "// biome-ignore-all lint/suspicious/noTemplateCurlyInString: formatString documents its ${} syntax.\n" +
    `/** The catalog this renderer draws, as the context entry posts it and \`a2ui/v1/catalog.json\` holds it. */\n` +
    `export const A2UI_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n`,
);
console.log(`catalog: ${JSON.stringify(catalog).length} chars compact`);
